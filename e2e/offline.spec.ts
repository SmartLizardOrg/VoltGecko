import { expect, test } from '@playwright/test';
import { jsPDF } from 'jspdf';

test('production PWA reopens, edits, imports PDF and exports with photos completely offline', async ({page,context})=>{
  test.setTimeout(90_000);
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>Object.defineProperty(window,'showSaveFilePicker',{value:undefined,configurable:true}));
  await page.goto('http://localhost:4173/');
  await expect(page.locator('.floor-device')).toHaveCount(8);
  await expect(page.getByText('Offline használatra kész',{exact:true})).toBeVisible({timeout:45_000});
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
  await page.reload();
  await expect(page.locator('.floor-device')).toHaveCount(8);
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true);
  await page.locator('.floor-device').first().click();
  await page.getByLabel('Eszköz neve',{exact:true}).fill('Helyszíni fotóval');
  await page.locator('.photo-upload input').setInputFiles({name:'helyszin.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jf1kAAAAASUVORK5CYII=','base64')});
  await expect(page.locator('.photo-grid img')).toHaveCount(1);
  await expect(page.getByText('Ezen az eszközön mentve',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Kijelölés bezárása',exact:true}).click();
  await context.setOffline(true);
  await page.reload();
  await expect(page.locator('.floor-device')).toHaveCount(8);
  await expect(page.locator('.statusbar').getByText('Offline',{exact:true})).toBeVisible();
  await page.locator('.floor-device').first().click();
  await expect(page.getByLabel('Eszköz neve',{exact:true})).toHaveValue('Helyszíni fotóval');
  await expect(page.locator('.photo-grid img')).toHaveJSProperty('complete',true);
  await page.getByLabel('Eszköz megjegyzése',{exact:true}).fill('Internet nélkül rögzítve.');
  await page.getByRole('button',{name:'Kijelölés bezárása',exact:true}).click();
  const pdf=new jsPDF();pdf.text('Floor 1',20,20);pdf.addPage();pdf.text('Floor 2',20,20);
  await page.locator('input[type=file][accept="application/pdf,image/png,image/jpeg"]').setInputFiles({name:'ketoldalas.pdf',mimeType:'application/pdf',buffer:Buffer.from(pdf.output('arraybuffer'))});
  await expect(page.getByLabel('Aktív tervlap',{exact:true}).locator('option')).toHaveCount(3,{timeout:25_000});
  await page.getByRole('button',{name:'Mentés és export',exact:true}).click();
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'Projektfájl mentése',exact:false}).first().click();
  const download=await downloadEvent;
  expect(download.suggestedFilename()).toMatch(/\.eplan$/);
  await download.saveAs('tmp/qa/offline-roundtrip.eplan');
  await expect(page.locator('.busy-overlay')).toHaveCount(0);
  await page.getByRole('button',{name:'Mentés és export',exact:true}).click();
  const exportEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'PDF a megrendelőnek',exact:false}).click();
  const output=await exportEvent;
  expect(output.suggestedFilename()).toMatch(/\.pdf$/);
  await output.saveAs('tmp/qa/offline-client.pdf');
  await expect(page.locator('.busy-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});
